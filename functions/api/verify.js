/**
 * GET /api/verify — SpinWave MVP certificate verifier (2026-10-29),
 * public, read-only, no sign-in required.
 * ?id=<record id or certificate id> and/or ?hash=<Base tx hash>.
 * Statuses, kept distinct on purpose:
 *   verified      — record found, state is certified, anchor_tx is
 *                   present, and a supplied hash matches it.
 *   invalid       — a record/certificate was found, but a supplied
 *                   hash does NOT match its confirmed anchor_tx, or
 *                   the record is presented as certified without a
 *                   confirmed anchor. `failed_check` names which.
 *   not_certified — record found, but no confirmed anchor yet
 *                   (anchoring pending, or upload pending). Not
 *                   "invalid": the work is real, the certificate
 *                   is not ready.
 *   not_found     — no record matches the supplied id/certificate/
 *                   hash. Not "invalid": nothing to check against.
 * D7/D8/D9 (2026-10-29, chosen as most secure): a supplied document
 * fingerprint must match the record's anchored fingerprint, and a
 * record verifies only with >= 12 Base confirmations recorded.
 * The full certificate JSON document itself is generated by the
 * pipeline, not here — this verifier checks the record + anchor +
 * fingerprint + depth, which is the load-bearing check a stranger
 * needs first. A tampered copy must return invalid, never verified.
 */

function json(body, status) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { 'Content-Type': 'application/json' },
  });
}

export async function onRequestGet({ request, env }) {
  if (!env.SPINWAVE_DB) return json({ error: 'not_configured' }, 500);
  const url = new URL(request.url);
  const id = (url.searchParams.get('id') || '').trim();
  const hash = (url.searchParams.get('hash') || '').trim().toLowerCase();
  const fingerprint = (url.searchParams.get('fingerprint') || '').trim().toLowerCase();
  if (!id && !hash && !fingerprint) return json({ error: 'bad_request' }, 400);
  const db = env.SPINWAVE_DB;
  await db
    .prepare(
      'CREATE TABLE IF NOT EXISTS records (id TEXT PRIMARY KEY, title TEXT, authors TEXT, version TEXT, scholar_wallet TEXT, state TEXT, anchor_tx TEXT, anchored_at INTEGER, certificate_id TEXT, created_at INTEGER)',
    )
    .run();
  // D7/D8/D9 columns, added to the pre-existing table without dropping it.
  // ALTER on an existing column throws in D1 — caught and ignored, so a
  // second deploy does not fail on its own migration.
  for (const col of ['document_fingerprint TEXT', 'anchor_confirmations INTEGER', 'anchor_status TEXT']) {
    try {
      await db.prepare(`ALTER TABLE records ADD COLUMN ${col}`).run();
    } catch {}
  }
  let row = null;
  if (id) {
    row = await db
      .prepare(
        'SELECT id, title, authors, version, scholar_wallet, state, anchor_tx, anchored_at, certificate_id, created_at, document_fingerprint, anchor_confirmations, anchor_status FROM records WHERE id = ? OR certificate_id = ?',
      )
      .bind(id, id)
      .first();
  }
  if (!row && hash) {
    row = await db
      .prepare(
        'SELECT id, title, authors, version, scholar_wallet, state, anchor_tx, anchored_at, certificate_id, created_at, document_fingerprint, anchor_confirmations, anchor_status FROM records WHERE anchor_tx = ?',
      )
      .bind(hash)
      .first();
  }
  if (!row) {
    return json(
      { status: 'not_found', message: 'No SpinWave record matches that certificate or hash.' },
      200,
    );
  }
  const anchor = (row.anchor_tx || '').toLowerCase();
  if (hash && anchor && hash !== anchor) {
    return json(
      {
        status: 'invalid',
        failed_check: 'hash_mismatch',
        message: 'The supplied hash does not match this record\'s confirmed anchor.',
        record: { id: row.id, title: row.title, state: row.state },
      },
      200,
    );
  }
  if (!anchor) {
    return json(
      {
        status: 'not_certified',
        message: 'This record exists but has no confirmed anchor yet, so it is not certified.',
        record: { id: row.id, title: row.title, state: row.state },
      },
      200,
    );
  }
  if (row.state !== 'certified') {
    return json(
      {
        status: 'invalid',
        failed_check: 'state_not_certified',
        message: 'This record has an anchor but is not marked certified, so a certificate for it does not verify.',
        record: { id: row.id, title: row.title, state: row.state },
      },
      200,
    );
  }
  // D7/D8: if a document fingerprint is supplied, it must match the
  // fingerprint anchored for this record. The anchor's subject is the
  // hash of the final validated document bytes — change one byte and
  // the old anchor no longer matches. A mismatch is INVALID, never
  // verified, even if every other identifier matches.
  if (fingerprint && row.document_fingerprint && fingerprint !== row.document_fingerprint.toLowerCase()) {
    return json(
      {
        status: 'invalid',
        failed_check: 'fingerprint_mismatch',
        message: 'The supplied document fingerprint does not match this record\'s anchored document.',
        record: { id: row.id, title: row.title, state: row.state },
      },
      200,
    );
  }
  // D9: 12 Base confirmations + receipt success + reorg check, chosen
  // as the most secure practical standard (see decisions round 2).
  // A certified record without a recorded confirmation depth is NOT
  // verified — the pipeline must record >= 12 before marking certified,
  // and if a reorg drops the anchor the pipeline returns the record to
  // 'anchoring pending' instead of leaving a certificate standing.
  const confirmations = row.anchor_confirmations;
  if (confirmations == null || confirmations < 12) {
    return json(
      {
        status: 'not_certified',
        message:
          confirmations == null
            ? 'This record is marked certified but its anchor confirmation depth has not been recorded yet, so it does not verify.'
            : `This record's anchor has ${confirmations} of the required 12 Base confirmations, so its certificate is not ready yet.`,
        record: { id: row.id, title: row.title, state: row.state, anchor_confirmations: confirmations, confirmations_required: 12 },
      },
      200,
    );
  }
  return json(
    {
      status: 'verified',
      record: {
        id: row.id,
        title: row.title,
        authors: row.authors,
        version: row.version,
        state: row.state,
        anchor_tx: row.anchor_tx,
        anchored_at: row.anchored_at,
        certificate_id: row.certificate_id,
        document_fingerprint: row.document_fingerprint || null,
        anchor_confirmations: confirmations,
        confirmations_required: 12,
      },
      basescan_url: `https://basescan.org/tx/${row.anchor_tx}`,
      record_url: `/records?id=${encodeURIComponent(row.id)}`,
    },
    200,
  );
}
